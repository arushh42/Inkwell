<?php

/**
 * Language helpers.
 *
 * German is the default language and English a translation. Which versions
 * of a page really exist is stored in its shared "availableIn" field; pages
 * without it (site pages) count as available in both. A page written only in
 * English keeps its text in the default content file, so the German URL can
 * show it with a "only available in English" note (see inkwell_versions()).
 */

use Kirby\Cms\Page;

/**
 * URL of a path in the current language, e.g. lurl('write') → /de/write.
 * Kirby's url() only adds the language prefix for real pages, not for our
 * own routes (write, login, add-paper, …).
 */
function lurl(string $path = '', array $query = [], string|null $language = null): string
{
    $lang = $language ? kirby()->language($language) : kirby()->language();
    $url  = rtrim($lang?->url() ?? kirby()->url(), '/') . ($path !== '' ? '/' . ltrim($path, '/') : '');

    return $query === [] ? $url : $url . '?' . http_build_query($query);
}

/**
 * Translated text with singular/plural, e.g. inkwell_count('stories.count', 3).
 */
function inkwell_count(string $key, int $count, array $replace = []): string
{
    return tt($key . ($count === 1 ? '.one' : '.other'), null, ['count' => $count] + $replace);
}

/**
 * Formats a date in the current language. Accepts a timestamp, a date
 * string or a Kirby field. Uses PHP date() formats; for German the month
 * and day names are translated (no dependency on the intl extension).
 */
function inkwell_date(mixed $value, string $format): string
{
    if ($value instanceof \Kirby\Content\Field) {
        $value = $value->value();
    }
    $time = is_numeric($value) ? (int)$value : strtotime((string)$value);
    if ($time === false) {
        return '';
    }

    $de = kirby()->language()?->code() === 'de';
    if ($de) {
        // German conventions: "26. November 2026", "26. Nov."
        $format = strtr($format, ['M j, Y' => 'j. M Y', 'j F Y' => 'j. F Y', 'l, j F Y' => 'l, j. F Y', 'j M' => 'j. M']);
    }

    $text = date($format, $time);

    return $de ? strtr($text, [
        'January' => 'Januar', 'February' => 'Februar', 'March' => 'März', 'April' => 'April',
        'May' => 'Mai', 'June' => 'Juni', 'July' => 'Juli', 'August' => 'August',
        'September' => 'September', 'October' => 'Oktober', 'November' => 'November', 'December' => 'Dezember',
        'Jan' => 'Jan.', 'Feb' => 'Feb.', 'Mar' => 'März', 'Apr' => 'Apr.', 'Jun' => 'Juni', 'Jul' => 'Juli',
        'Aug' => 'Aug.', 'Sep' => 'Sept.', 'Oct' => 'Okt.', 'Nov' => 'Nov.', 'Dec' => 'Dez.',
        'Monday' => 'Montag', 'Tuesday' => 'Dienstag', 'Wednesday' => 'Mittwoch', 'Thursday' => 'Donnerstag',
        'Friday' => 'Freitag', 'Saturday' => 'Samstag', 'Sunday' => 'Sonntag',
    ]) : $text;
}

/**
 * Language codes this page really exists in, in order of preference.
 */
function inkwell_versions(Page $page): array
{
    $field = $page->content('de')->get('availablein');
    if ($field->isNotEmpty()) {
        return array_values(array_intersect(['de', 'en'], $field->split(',')));
    }

    return ['de', 'en'];
}

/**
 * True if the page exists in the current language (no fallback note needed).
 */
function inkwell_is_translated(Page $page, string|null $code = null): bool
{
    return in_array($code ?? kirby()->language()->code(), inkwell_versions($page), true);
}

/**
 * Display name of a language in the current interface language,
 * e.g. "Englisch" on German pages.
 */
function inkwell_lang_name(string $code): string
{
    return t('lang.name.' . $code);
}

/**
 * The current URL in another language (same path, same query string).
 */
function inkwell_switch_url(string $code): string
{
    $kirby = kirby();
    $path  = trim($kirby->request()->path()->toString(), '/');
    $parts = explode('/', $path);

    if (in_array($parts[0] ?? '', ['de', 'en'], true)) {
        array_shift($parts);
    }

    $query = $kirby->request()->query()->toArray();

    return lurl(implode('/', $parts), $query, $code);
}

/**
 * The stored abstract source (always English, generated by the DOI lookup)
 * shown in the current language.
 */
function inkwell_source_label(string $source): string
{
    if (preg_match('/^(.+) \((\d{4})\), licensed under (.+)$/', $source, $m)) {
        return tt('source.licensed', null, ['venue' => $m[1], 'year' => $m[2], 'license' => $m[3]]);
    }
    if (preg_match('/^arXiv preprint (\S+) \(arXiv metadata, CC0\)/', $source, $m)) {
        return tt('source.arxiv', null, ['id' => $m[1]]);
    }
    if ($source === 'arXiv via DataCite metadata (CC0)') {
        return t('source.datacite');
    }
    if (preg_match('/^Description written by (.+?)(?: for .+)?$/', $source, $m)) {
        return tt('source.member', null, ['name' => $m[1]]);
    }

    return $source;
}

/**
 * Saves one language version of a page (used by the writing studio and
 * "Add a paper"). $text holds the translatable fields, $shared the fields
 * that are the same in every language.
 *
 * Storage rule: the default (German) content file always holds the text of
 * the page's first version. So:
 *  - German text always goes into the default file. If that file still
 *    holds an English-only original, the English text is first moved into
 *    the English file, so nothing is overwritten.
 *  - English text goes into the English file, unless the page has no German
 *    version yet; then it stays in the default file.
 * Pages without an availableIn value count as available in both languages.
 */
function inkwell_save_version(Page $page, array $text, array $shared, string $lang): Page
{
    $default  = kirby()->defaultLanguage()->code();
    $versions = inkwell_versions($page);
    $now      = array_values(array_intersect(['de', 'en'], array_unique([...$versions, $lang])));

    if ($lang === $default) {
        if (!in_array($default, $versions, true)) {
            $original = array_intersect_key($page->content($default)->toArray(), array_change_key_case($text));
            $page     = $page->update($original, 'en');
        }

        return $page->update($text + $shared + ['availableIn' => $now], $default);
    }

    if (!in_array($default, $versions, true)) {
        return $page->update($text + $shared + ['availableIn' => $now], $default);
    }

    $page = $page->update($text, $lang);

    return $page->update($shared + ['availableIn' => $now], $default);
}
